import os
from debloat_checker import *

file_path = 'app.txt'


def read_app_list(path):
    # Try UTF-8 first (macOS/Linux shell redirect); fall back to UTF-16
    # (Windows PowerShell redirects as UTF-16LE, which would otherwise crash).
    for encoding in ('utf-8', 'utf-16'):
        try:
            with open(path, 'r', encoding=encoding) as f:
                return f.readlines()
        except (UnicodeDecodeError, UnicodeError):
            continue
    raise ValueError(f"Could not decode {path} as UTF-8 or UTF-16.")


if not os.path.exists(file_path):
    raise SystemExit(
        f"ERROR: '{file_path}' not found in this directory.\n"
        "Generate it from YOUR phone first (do not reuse a sample file):\n"
        "    adb shell pm list packages > app.txt"
    )

lines = read_app_list(file_path)

items = [line.replace('package:', '', 1).strip() for line in lines]
items = [i for i in items if i]  # drop blank lines

uninstall_list, remaining_list = checkDebloat(items)
uninstall_list.sort()

# Create directory if the directory does not exist
if not os.path.exists("output"):
    os.makedirs("output")

# --- Uninstall script -------------------------------------------------------
# Write the commands, then turn the file into a ready-to-run executable script.
# Any stale uninstall_list.sh (e.g. shipped with the repo) is replaced.
uninstall_txt = os.path.join("output", "uninstall_list.txt")
uninstall_sh = os.path.join("output", "uninstall_list.sh")
with open(uninstall_txt, 'w') as f_out:
    f_out.write('#!/bin/bash\n')
    f_out.write('# Generated by main.py - run it with: ./uninstall_list.sh  (or: bash uninstall_list.sh)\n')
    f_out.write('# Review the package list below before running. Rollback: ./restore_list.sh\n')
    # Write each item to the output file
    for item in uninstall_list:
        # adb is now configured in system PATH
        f_out.write('adb shell pm uninstall --user 0 ' + item + '\n')

if os.path.exists(uninstall_sh):
    os.remove(uninstall_sh)
os.rename(uninstall_txt, uninstall_sh)
os.chmod(uninstall_sh, 0o755)
print(f"Wrote {uninstall_sh} with {len(uninstall_list)} packages (executable).")

# --- Restore script (one-command rollback for the same packages) -------------
restore_sh = os.path.join("output", "restore_list.sh")
with open(restore_sh, 'w') as f_out:
    f_out.write('#!/bin/bash\n')
    f_out.write('# Generated by main.py - reinstalls everything uninstall_list.sh removes.\n')
    f_out.write('# Run it with: ./restore_list.sh  (or: bash restore_list.sh)\n')
    f_out.write('# Lines that fail are not system apps - reinstall those from the Play Store.\n')
    for item in uninstall_list:
        f_out.write('adb shell cmd package install-existing ' + item + '\n')
os.chmod(restore_sh, 0o755)
print(f"Wrote {restore_sh} with {len(uninstall_list)} packages (executable).")

# --- Remaining (untouched) packages ------------------------------------------
remaining_list.sort()

# Open the output file to write
with open("output/remaining_list.txt", 'w') as f_out:
    # Write each item to the output file
    for item in remaining_list:
        f_out.write(item + '\n')
print(f"Wrote output/remaining_list.txt with {len(remaining_list)} untouched packages.")
